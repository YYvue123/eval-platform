test('isolated publication: anonymous view and immediate withdrawal',async({page,request})=>{
  const login=await request.post('/api/auth/login',{data:{username:'admin',password:'admin123'}})
  const {access_token:token}=await login.json(),headers={Authorization:`Bearer ${token}`}
  const data=await (await request.get('/api/leaderboard/insights',{headers,params:{category:'finance',board:'special'}})).json()
  expect(data.items.length).toBe(3)
  const release=await request.post('/api/leaderboard/publications',{headers,data:{cohort_id:data.cohort_id,category:'finance',board:'special',title:'隔离验证 · 金融专项公开期数',public:true}})
  expect(release.ok()).toBeTruthy()
  const publication=await release.json()
  await page.goto(publication.public_path)
  await expect(page.getByRole('heading',{name:'隔离验证 · 金融专项公开期数'})).toBeVisible()
  await expect(page.locator('.public-chart canvas')).toBeVisible()
  await page.screenshot({path:resolve(shots,'public.png'),fullPage:true})
  expect((await request.post(`/api/leaderboard/publications/${publication.id}/withdraw`,{headers,data:{reason:'隔离测试完成后撤回'}})).ok()).toBeTruthy()
  await page.reload()
  await expect(page.getByRole('heading',{name:'此榜单当前不可查看'})).toBeVisible()
  await expect(page.locator('.public-chart')).toHaveCount(0)
})

