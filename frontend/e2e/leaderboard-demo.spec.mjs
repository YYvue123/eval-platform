import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import { resolve } from 'node:path'
const shots=resolve('../docs/delivery/leaderboard-screenshots')
test('real measured demo: charts, protocols, archive, CSV, evidence, responsive layout', async ({page,request})=>{
  const errors=[]; page.on('pageerror',e=>errors.push(e.message))
  const login=await request.post('/api/auth/login',{data:{username:'admin',password:'admin123'}})
  expect(login.ok()).toBeTruthy()
  const {access_token:token}=await login.json()
  const api=await request.get('/api/leaderboard/insights',{headers:{Authorization:`Bearer ${token}`}})
  expect(api.ok()).toBeTruthy()
  const measured=await api.json()
  expect(measured.items.length).toBe(3)
  expect(measured.dimensions.length).toBe(4)
  expect(measured.history.length).toBeGreaterThanOrEqual(6)
  expect((await request.get('/api/leaderboard/insights')).status()).toBe(401)
  await page.addInitScript(token=>{sessionStorage.setItem('eval_token',token);sessionStorage.setItem('eval_username','admin');sessionStorage.setItem('eval_role','admin')},token)
  await page.goto('/leaderboard')
  await expect(page.getByRole('heading',{name:'让每一次比较，都有依据.'})).toBeVisible()
  await expect(page.locator('.selection-bar')).toContainText('3/5')
  await mkdir(shots,{recursive:true})
  await page.screenshot({path:resolve(shots,'overview.png'),fullPage:true})
  for(const [label,file] of [['能力雷达','radar'],['能力矩阵','matrix'],['质量与效率','efficiency'],['历史记录','history']]){
    await page.getByRole('tab',{name:label,exact:true}).click()
    const pane=page.getByRole('tabpanel',{name:label,exact:true})
    await expect(pane.locator('canvas').first()).toBeVisible()
    await pane.scrollIntoViewIfNeeded()
    await page.screenshot({path:resolve(shots,`${file}.png`)})
  }
  const downloadPromise=page.waitForEvent('download')
  await page.getByRole('button',{name:'导出当前结果',exact:true}).click()
  const download=await downloadPromise
  expect(download.suggestedFilename()).toContain(measured.cohort_id)
  await download.saveAs(resolve(shots,'export.csv'))
  await page.getByPlaceholder('搜索模型、机构').fill('不存在的配置')
  await expect(page.getByText('暂无符合条件的完整实测结果')).toBeVisible()
  await page.getByPlaceholder('搜索模型、机构').fill('')
  await page.getByText('能力档案',{exact:true}).click()
  await expect(page.getByText('— 未测').first()).toBeVisible()
  await page.screenshot({path:resolve(shots,'profiles.png'),fullPage:true})
  await page.getByText('可比排名',{exact:true}).click()
  await page.getByRole('button',{name:measured.items[0].model_name,exact:true}).click()
  await expect(page.getByRole('dialog',{name:'评测证据'})).toContainText(measured.cohort_id)
  await page.getByRole('dialog',{name:'评测证据'}).getByRole('button',{name:'关闭此对话框'}).click()
  const single=measured.cohorts.find(c=>c.count===1)
  await page.locator('.filter-grid .el-select').first().click()
  await page.getByRole('option',{name:`${single.label} · ${single.count} 个配置`,exact:true}).click()
  await expect(page.locator('.selection-bar')).toContainText('1/5')
  await page.getByRole('tab',{name:'能力雷达',exact:true}).click()
  await expect(page.getByText('暂不能绘制雷达图')).toBeVisible()
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:resolve(shots,'mobile.png'),fullPage:true})
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+2)
  expect(overflow).toBeFalsy()
  expect(errors).toEqual([])
})
